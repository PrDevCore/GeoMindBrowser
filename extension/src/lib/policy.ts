/**
 * Policy mirror used by the extension for previews and by tests that evaluate
 * the generated PAC. The companion is authoritative at runtime.
 */

export type Action = "direct" | "route" | "block";
export type RuleAction = "route" | "block";

export interface PolicyRule {
  readonly id: string;
  readonly host: string;
  readonly action: RuleAction;
  readonly exit?: string;
  readonly priority?: number;
}

export interface PolicyDoc {
  readonly version: 1;
  readonly defaultAction: "direct";
  readonly rules: readonly PolicyRule[];
}

export interface Decision {
  readonly action: Action;
  readonly exit: string;
  readonly ruleId: string;
}

export const BLOCK_PROXY = "SOCKS5 127.0.0.1:9";

export const PAC_HEADER = "// Generated by GeoMind. Do not edit.\n";
export const PAC_PREFIX = `${PAC_HEADER}var RULES = `;
export const PAC_BODY = `function FindProxyForURL(url, host) {
  host = String(host).toLowerCase();
  if (host.charAt(host.length - 1) === ".") host = host.slice(0, -1);
  for (var i = 0; i < RULES.length; i++) {
    var r = RULES[i];
    if (r.host === host) return r.proxy;
    if (r.host.slice(0, 2) === "*.") {
      var suffix = r.host.slice(1);
      if (host.length > suffix.length && host.slice(-suffix.length) === suffix) return r.proxy;
    }
  }
  return "DIRECT";
}
`;

export class PolicyError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "PolicyError";
  }
}

interface CompiledRule {
  readonly id: string;
  readonly host: string;
  readonly kind: "exact" | "wildcard";
  readonly labels: number;
  readonly action: Action;
  readonly exit: string;
  readonly priority: number;
  readonly index: number;
}

interface CompiledPattern {
  readonly kind: "exact" | "wildcard";
  readonly host: string;
  readonly labels: number;
}

const ID_PATTERN = /^[A-Za-z0-9._-]{1,64}$/;
const IPV4_PATTERN = /^\d{1,3}(\.\d{1,3}){3}$/;
const FORBIDDEN_HOST_CHARS = /[/:@[\]%\\\s]/;
const MAX_PRIORITY = 1_000_000;

export class Policy {
  readonly #rules: readonly CompiledRule[];

  private constructor(rules: readonly CompiledRule[]) {
    this.#rules = rules;
  }

  static compile(input: unknown, knownExits: readonly string[]): Policy {
    const doc = parseDoc(input);
    const known = new Set(knownExits);
    const seen = new Set<string>();
    const rules: CompiledRule[] = [];

    doc.rules.forEach((rule, index) => {
      if (seen.has(rule.id)) {
        throw new PolicyError(`duplicate rule id "${rule.id}"`);
      }
      seen.add(rule.id);

      const pattern = compilePattern(rule.host);
      let action: Action = rule.action;
      let exit = rule.exit ?? "";
      if (action === "route" && !known.has(exit)) {
        // Unknown exits fail closed, and never fall back to direct.
        action = "block";
        exit = "";
      }

      rules.push({
        id: rule.id,
        host: pattern.host,
        kind: pattern.kind,
        labels: pattern.labels,
        action,
        exit,
        priority: rule.priority ?? 0,
        index,
      });
    });

    rules.sort(compareRules);
    return new Policy(rules);
  }

  match(rawHost: string): Decision {
    const host = normalizeHost(rawHost);
    for (const rule of this.#rules) {
      if (rule.kind === "exact") {
        if (host === rule.host) return decisionFor(rule);
        continue;
      }
      const suffix = `.${rule.host}`;
      if (host.length > suffix.length && host.endsWith(suffix)) return decisionFor(rule);
    }
    return { action: "direct", exit: "", ruleId: "" };
  }

  /** Normalized route patterns, deduplicated, in match order. */
  headerTargets(): readonly { readonly host: string; readonly kind: "exact" | "wildcard" }[] {
    const seen = new Set<string>();
    const targets: { host: string; kind: "exact" | "wildcard" }[] = [];
    for (const rule of this.#rules) {
      if (rule.action !== "route") continue;
      const key = `${rule.kind}:${rule.host}`;
      if (seen.has(key)) continue;
      seen.add(key);
      targets.push({ host: rule.host, kind: rule.kind });
    }
    return targets;
  }

  buildPac(proxyAddr: string): string {
    validateProxyAddr(proxyAddr);
    return buildPac(this.#rules, proxyAddr);
  }
}

function decisionFor(rule: CompiledRule): Decision {
  if (rule.action === "block") return { action: "block", exit: "", ruleId: rule.id };
  return { action: rule.action, exit: rule.exit, ruleId: rule.id };
}

function compareRules(a: CompiledRule, b: CompiledRule): number {
  if (a.kind !== b.kind) return a.kind === "exact" ? -1 : 1;
  if (a.kind === "wildcard") {
    if (a.labels !== b.labels) return b.labels - a.labels;
    if (a.host.length !== b.host.length) return b.host.length - a.host.length;
  }
  if (a.priority !== b.priority) return b.priority - a.priority;
  return a.index - b.index;
}

function parseDoc(input: unknown): PolicyDoc {
  const obj = asRecord(input, "policy");
  checkKeys(obj, ["version", "defaultAction", "rules"], "policy");
  if (obj.version !== 1) throw new PolicyError("policy: version must be 1");
  if (obj.defaultAction !== "direct") {
    throw new PolicyError('policy: defaultAction must be "direct"');
  }
  if (!Array.isArray(obj.rules)) throw new PolicyError("policy: rules must be an array");
  const rules = obj.rules.map((rule, index) => parseRule(rule, index));
  return { version: 1, defaultAction: "direct", rules };
}

function parseRule(input: unknown, index: number): PolicyRule {
  const where = `rule ${index}`;
  const obj = asRecord(input, where);
  checkKeys(obj, ["id", "host", "action", "exit", "priority"], where);

  const id = obj.id;
  if (typeof id !== "string" || !ID_PATTERN.test(id)) {
    throw new PolicyError(`${where}: invalid id`);
  }
  const host = obj.host;
  if (typeof host !== "string") throw new PolicyError(`${where}: host must be a string`);

  const action = obj.action;
  if (action !== "route" && action !== "block") {
    throw new PolicyError(`${where}: unknown action`);
  }

  const exit = obj.exit;
  let exitText: string | undefined;
  if (action === "route") {
    if (typeof exit !== "string" || exit.length === 0 || exit.length > 64) {
      throw new PolicyError(`${where}: route requires an exit`);
    }
    exitText = exit;
  } else if (exit !== undefined) {
    throw new PolicyError(`${where}: block must not name an exit`);
  }

  const priority = obj.priority;
  if (
    priority !== undefined &&
    (typeof priority !== "number" || !Number.isInteger(priority) || Math.abs(priority) > MAX_PRIORITY)
  ) {
    throw new PolicyError(`${where}: invalid priority`);
  }

  const parsed: {
    id: string;
    host: string;
    action: RuleAction;
    exit?: string;
    priority?: number;
  } = { id, host, action };
  if (exitText !== undefined) parsed.exit = exitText;
  if (priority !== undefined) parsed.priority = priority;
  return parsed;
}

function asRecord(value: unknown, where: string): Record<string, unknown> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new PolicyError(`${where}: expected an object`);
  }
  return value as Record<string, unknown>;
}

function checkKeys(obj: Record<string, unknown>, allowed: readonly string[], where: string): void {
  for (const key of Object.keys(obj)) {
    if (!allowed.includes(key)) throw new PolicyError(`${where}: unknown field "${key}"`);
  }
}

function compilePattern(raw: string): CompiledPattern {
  if (raw.length === 0) throw new PolicyError("host: empty pattern");
  if (raw.startsWith("*.")) {
    const suffix = normalizeHost(raw.slice(2));
    return { kind: "wildcard", host: suffix, labels: suffix.split(".").length };
  }
  if (raw.includes("*")) {
    throw new PolicyError("host: wildcard must be the leading label");
  }
  return { kind: "exact", host: normalizeHost(raw), labels: 0 };
}

function normalizeHost(raw: string): string {
  if (raw.length === 0) throw new PolicyError("host: empty");
  if (raw.trim() !== raw) throw new PolicyError("host: surrounding whitespace");

  let host = raw.toLowerCase();
  if (host.endsWith(".")) host = host.slice(0, -1);
  if (host.length === 0 || host.includes("*")) throw new PolicyError(`host: ${raw}`);
  if (FORBIDDEN_HOST_CHARS.test(host)) throw new PolicyError(`host: ${raw}`);
  if (host.length > 253) throw new PolicyError("host: too long");

  let ascii: string;
  try {
    const url = new URL(`http://${host}/`);
    if (
      url.username !== "" ||
      url.password !== "" ||
      url.port !== "" ||
      url.pathname !== "/" ||
      url.search !== "" ||
      url.hash !== ""
    ) {
      throw new PolicyError(`host: ${raw}`);
    }
    ascii = url.hostname;
  } catch {
    throw new PolicyError(`host: ${raw}`);
  }

  if (ascii.length > 253) throw new PolicyError("host: too long");
  if (IPV4_PATTERN.test(ascii) || ascii.includes(":")) {
    throw new PolicyError("host: IP literals are not supported");
  }
  for (const label of ascii.split(".")) {
    if (!validLabel(label)) throw new PolicyError(`host: bad label "${label}"`);
  }
  return ascii;
}

function validLabel(label: string): boolean {
  if (label.length < 1 || label.length > 63) return false;
  if (label.startsWith("-") || label.endsWith("-")) return false;
  return /^[a-z0-9-]+$/.test(label);
}

function validateProxyAddr(addr: string): void {
  const match = /^127\.0\.0\.1:([0-9]{1,5})$/.exec(addr);
  const portText = match?.[1];
  if (portText === undefined) {
    throw new PolicyError("proxy address must be 127.0.0.1:port");
  }
  const port = Number(portText);
  if (port < 1 || port > 65535 || port === 9) {
    throw new PolicyError(`unusable proxy port ${portText}`);
  }
}

function buildPac(rules: readonly CompiledRule[], proxyAddr: string): string {
  const encoded = rules.map((rule) => ({
    host: rule.kind === "wildcard" ? `*.${rule.host}` : rule.host,
    proxy: rule.action === "block" ? BLOCK_PROXY : `SOCKS5 ${proxyAddr}`,
  }));

  // Must stay byte-identical to the Go generator: both are checked against the
  // same golden PAC.
  return `${PAC_PREFIX}${JSON.stringify(encoded)};\n${PAC_BODY}`;
}
