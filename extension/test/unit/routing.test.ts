import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it, vi } from "vitest";
import { installPac, pacSatisfied, validatePac } from "../../src/background/pac";
import { webRtcPolicySatisfied, WEBRTC_POLICY } from "../../src/background/privacy";
import { BLOCK_PROXY, PAC_BODY, PAC_PREFIX, Policy } from "../../src/lib/policy";

const fixturesRoot = fileURLToPath(new URL("../../../shared/fixtures/policy/", import.meta.url));
const PROXY = "127.0.0.1:1080";

interface ValidFixture {
  readonly knownExits: readonly string[];
  readonly policy: unknown;
}

function readFixture(file: string): ValidFixture {
  return JSON.parse(readFileSync(path.join(fixturesRoot, "valid", file), "utf8")) as ValidFixture;
}

function basicPac(): string {
  const fx = readFixture("basic.json");
  return Policy.compile(fx.policy, fx.knownExits).buildPac(PROXY);
}

describe("PAC validation before install", () => {
  it("accepts the generated PAC and reports its rules", () => {
    const validated = validatePac(basicPac());
    expect(validated.proxyAddr).toBe(PROXY);
    expect(validated.routeCount).toBe(2);
    expect(validated.blockCount).toBe(0);
    expect(validated.rules.map((r) => r.host)).toEqual(["shop.example.org", "*.example.com"]);
  });

  it("reports a block-only PAC with no proxy target", () => {
    const pac = `${PAC_PREFIX}${JSON.stringify([{ host: "*.ads.test", proxy: BLOCK_PROXY }])};\n${PAC_BODY}`;
    const validated = validatePac(pac);
    expect(validated.proxyAddr).toBeNull();
    expect(validated.blockCount).toBe(1);
  });

  it("rejects a modified header, body, or JSON", () => {
    const pac = basicPac();
    expect(() => validatePac(pac.replace("Generated by GeoMind", "Generated elsewhere"))).toThrow(
      "header is missing",
    );
    expect(() => validatePac(pac.replace(PAC_BODY, `${PAC_BODY}// injected\n`))).toThrow(
      "interpreter was modified",
    );
    expect(() => validatePac(pac.replace('"proxy":"SOCKS5', '"proxy":SOCKS5'))).toThrow(
      "not valid JSON",
    );
  });

  it("rejects rules that do not fail closed", () => {
    const direct = `${PAC_PREFIX}${JSON.stringify([{ host: "a.test", proxy: "DIRECT" }])};\n${PAC_BODY}`;
    expect(() => validatePac(direct)).toThrow("not loopback SOCKS5");

    const remote = `${PAC_PREFIX}${JSON.stringify([{ host: "a.test", proxy: "SOCKS5 10.0.0.1:1080" }])};\n${PAC_BODY}`;
    expect(() => validatePac(remote)).toThrow("not loopback SOCKS5");

    const two = `${PAC_PREFIX}${JSON.stringify([
      { host: "a.test", proxy: "SOCKS5 127.0.0.1:1080" },
      { host: "b.test", proxy: "SOCKS5 127.0.0.1:1081" },
    ])};\n${PAC_BODY}`;
    expect(() => validatePac(two)).toThrow("more than one proxy");
  });

  it("rejects extra DIRECT returns and unsafe hosts", () => {
    const extra = basicPac().replace('return "DIRECT";', 'if (host === "x") return "DIRECT";\n  return "DIRECT";');
    expect(() => validatePac(extra)).toThrow("interpreter was modified");

    const unsafe = `${PAC_PREFIX}${JSON.stringify([{ host: "a.test; DIRECT", proxy: BLOCK_PROXY }])};\n${PAC_BODY}`;
    expect(() => validatePac(unsafe)).toThrow("unsafe host");
  });
});

describe("WebRTC policy check", () => {
  it("requires this extension to control the policy with direct UDP disabled", () => {
    expect(webRtcPolicySatisfied({ levelOfControl: "controlled_by_this_extension", value: WEBRTC_POLICY })).toBe(true);
    expect(webRtcPolicySatisfied({ levelOfControl: "controllable_by_this_extension", value: WEBRTC_POLICY })).toBe(
      false,
    );
    expect(webRtcPolicySatisfied({ levelOfControl: "controlled_by_this_extension", value: "default" })).toBe(false);
  });
});

describe("PAC proxy drift", () => {
  const pac = basicPac();
  const ours = {
    levelOfControl: "controlled_by_this_extension",
    mode: "pac_script",
    pac,
    mandatory: true,
  };

  it("accepts only this extension's mandatory PAC byte for byte", () => {
    expect(pacSatisfied(ours, pac)).toBe(true);
    expect(pacSatisfied({ ...ours, levelOfControl: "controllable_by_this_extension" }, pac)).toBe(false);
    expect(pacSatisfied({ ...ours, levelOfControl: "controlled_by_other_extensions" }, pac)).toBe(false);
    expect(pacSatisfied({ ...ours, mode: "direct", pac: undefined }, pac)).toBe(false);
    expect(pacSatisfied({ ...ours, pac: pac.replace("example", "example.org") }, pac)).toBe(false);
    expect(pacSatisfied({ ...ours, mandatory: false }, pac)).toBe(false);
  });

  function stubProxy(levelOfControl: string, value: unknown): void {
    vi.stubGlobal("chrome", {
      proxy: {
        settings: {
          set: (_options: unknown, callback: () => void) => callback(),
          get: (_options: unknown, callback: (details: unknown) => void) =>
            callback({ levelOfControl, value }),
        },
      },
      runtime: {},
    });
  }

  afterEach(() => {
    vi.unstubAllGlobals();
  });

  it("accepts an install that reads back as our mandatory PAC", async () => {
    stubProxy("controlled_by_this_extension", { mode: "pac_script", pacScript: { data: pac, mandatory: true } });
    const validated = await installPac(pac);
    expect(validated.routeCount).toBe(2);
  });

  it("fails when the setting reads back as direct", async () => {
    stubProxy("controlled_by_this_extension", { mode: "direct" });
    await expect(installPac(pac)).rejects.toThrow("did not stay under extension control");
  });

  it("fails when another controller owns the setting", async () => {
    stubProxy("not_controllable", { mode: "pac_script", pacScript: { data: pac, mandatory: true } });
    await expect(installPac(pac)).rejects.toThrow("did not stay under extension control");
  });
});
