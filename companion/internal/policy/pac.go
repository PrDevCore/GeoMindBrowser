package policy

import (
	"encoding/json"
	"fmt"
	"strconv"
	"strings"
)

// blockProxy is a loopback port nothing listens on. Pairing it with no fallback
// makes a blocked host fail instead of escaping directly.
const blockProxy = "SOCKS5 127.0.0.1:9"

const pacBody = `function FindProxyForURL(url, host) {
  host = String(host).toLowerCase();
  if (host.charAt(host.length - 1) === ".") host = host.slice(0, -1);
  for (var i = 0; i < RULES.length; i++) {
    var r = RULES[i];
    if (r.host === host) return r.proxy;
    if (r.host.slice(0, 2) === "*.") {
      var suffix = r.host.slice(1);
      if (host.length > suffix.length && host.slice(-suffix.length) === suffix) return r.proxy;
    }
  }
  return "DIRECT";
}
`

type pacRule struct {
	Host  string `json:"host"`
	Proxy string `json:"proxy"`
}

// PAC generates the proxy auto-config script for this policy. The script has no
// DIRECT fallback for matched hosts: route rules map to the proxy and block
// rules map to a dead loopback port.
func (s *Store) PAC(proxyAddr string) (string, error) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	if !s.loaded {
		return "", ErrNotLoaded
	}
	return s.pacLocked(proxyAddr)
}

// pacLocked builds and validates the PAC. The caller holds the read lock.
func (s *Store) pacLocked(proxyAddr string) (string, error) {
	if err := validateProxyAddr(proxyAddr); err != nil {
		return "", err
	}
	pac, err := buildPAC(s.rules, proxyAddr)
	if err != nil {
		return "", err
	}
	if err := ValidatePAC(pac, proxyAddr); err != nil {
		return "", err
	}
	return pac, nil
}

func buildPAC(rules []compiledRule, proxyAddr string) (string, error) {
	encoded := make([]pacRule, 0, len(rules))
	for _, r := range rules {
		host := r.host
		if r.kind == patternWildcard {
			host = "*." + r.host
		}
		proxy := "SOCKS5 " + proxyAddr
		if r.action == ActionBlock {
			proxy = blockProxy
		}
		encoded = append(encoded, pacRule{Host: host, Proxy: proxy})
	}
	data, err := json.Marshal(encoded)
	if err != nil {
		return "", fmt.Errorf("encode pac rules: %w", err)
	}

	var b strings.Builder
	b.WriteString("// Generated by GeoMind. Do not edit.\n")
	b.WriteString("var RULES = ")
	b.Write(data)
	b.WriteString(";\n")
	b.WriteString(pacBody)
	return b.String(), nil
}

// ValidatePAC re-reads the generated rule table and enforces the fail-closed
// shape: no rule maps to DIRECT and the only DIRECT return is the default.
func ValidatePAC(pac, proxyAddr string) error {
	const marker = "var RULES = "
	start := strings.Index(pac, marker)
	if start < 0 {
		return fmt.Errorf("%w: pac has no rule table", ErrInvalidPolicy)
	}
	rest := pac[start+len(marker):]
	end := strings.Index(rest, ";\n")
	if end < 0 {
		return fmt.Errorf("%w: pac rule table is not terminated", ErrInvalidPolicy)
	}
	var rules []pacRule
	if err := json.Unmarshal([]byte(rest[:end]), &rules); err != nil {
		return fmt.Errorf("%w: pac rule table: %w", ErrInvalidPolicy, err)
	}

	allowed := map[string]struct{}{
		"SOCKS5 " + proxyAddr: {},
		blockProxy:            {},
	}
	for _, r := range rules {
		if _, ok := allowed[r.Proxy]; !ok {
			return fmt.Errorf("%w: pac rule %q maps to %q", ErrInvalidPolicy, r.Host, r.Proxy)
		}
	}
	if !strings.Contains(pac, "function FindProxyForURL(url, host)") {
		return fmt.Errorf("%w: pac has no FindProxyForURL", ErrInvalidPolicy)
	}
	if strings.Count(pac, `return "DIRECT";`) != 1 {
		return fmt.Errorf("%w: pac must have exactly one DIRECT return", ErrInvalidPolicy)
	}
	if !strings.HasSuffix(pac, pacBody) {
		return fmt.Errorf("%w: pac body was modified", ErrInvalidPolicy)
	}
	return nil
}

func validateProxyAddr(addr string) error {
	host, portStr, err := splitHostPort(addr)
	if err != nil {
		return err
	}
	if host != "127.0.0.1" {
		return fmt.Errorf("%w: proxy must bind IPv4 loopback, got %q", ErrInvalidPolicy, host)
	}
	for _, c := range portStr {
		if c < '0' || c > '9' {
			return fmt.Errorf("%w: bad proxy port %q", ErrInvalidPolicy, portStr)
		}
	}
	port, err := strconv.Atoi(portStr)
	if err != nil || port < 1 || port > 65535 || port == 9 {
		return fmt.Errorf("%w: unusable proxy port %q", ErrInvalidPolicy, portStr)
	}
	return nil
}

func splitHostPort(addr string) (string, string, error) {
	i := strings.LastIndex(addr, ":")
	if i <= 0 || i == len(addr)-1 {
		return "", "", fmt.Errorf("%w: proxy address must be host:port", ErrInvalidPolicy)
	}
	return addr[:i], addr[i+1:], nil
}
